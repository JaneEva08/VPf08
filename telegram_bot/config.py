"""Конфигурация бота: ключи и настройки берутся из .env, в коде секретов нет."""
import os

from dotenv import load_dotenv

load_dotenv()


def _required(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"Переменная окружения {name} не задана. Скопируйте .env.example в .env и заполните её.")
    return value


TELEGRAM_API_TOKEN = _required("TELEGRAM_API_TOKEN")
OPENAI_API_KEY = _required("OPENAI_API_KEY")
OPENAI_MODEL = os.getenv("OPENAI_MODEL", "gpt-4o-mini")
MCP_SERVER_URL = os.getenv("MCP_SERVER_URL", "http://localhost:8000")

# Сколько последних сообщений диалога отправляется в LLM (контекст)
HISTORY_LIMIT = 20
# Максимум последовательных вызовов инструментов за один запрос пользователя
MAX_TOOL_ROUNDS = 5

SYSTEM_PROMPT = """Ты — дружелюбный помощник книжного магазина. Ты работаешь с каталогом книг через инструменты (MCP).

Правила:
- Для любых данных о книгах, ценах и расчётов используй инструменты, ничего не выдумывай.
- Если нужен ID книги, но пользователь назвал только название — сначала найди книгу, затем действуй по её ID.
- Перед удалением книги убедись, что пользователь явно этого просит.
- Если запрос непонятен или не хватает данных (например, не указана цена новой книги) — задай уточняющий вопрос.
- Учитывай предыдущие сообщения диалога: «эта книга», «а похожие?» относятся к последнему обсуждаемому товару.
- Похожими считай книги того же жанра или автора.
- Цены указывай в рублях. Отвечай на русском языке, структурированно: списки, ID, название, автор, жанр, цена.
- Если результатов много, покажи первые 10 и предложи уточнить запрос."""
